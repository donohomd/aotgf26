// Offline support for the schedule.
//
// PAGE FILES (index.html, logo, icons, manifest): served from the stored copy
// immediately, then refreshed from the network in the background, so page-code
// changes take effect on the next visit without ever reloading an open page.
//
// SCHEDULE DATA (schedule.json): served from the stored copy. The page itself
// checks version.json and stores newer data (see index.html), so this worker
// never silently swaps data underneath the visitor. version.json and any
// request with a query string (?v=, ?t=) always go straight to the network.
//
// SW_VERSION is generated by the publish compiler from the page files' content,
// so any change to them installs into a fresh cache (never a half-updated one).
const SW_VERSION = 'shell-f926570c0299f359';

// Several sites can share one origin (e.g. every GitHub Pages project under
// username.github.io), so every cache name includes this worker's scope.
const SCOPE = self.registration.scope;
const SHELL_PREFIX = 'rotapas-shell:' + SCOPE + ':';
const SHELL_CACHE = SHELL_PREFIX + SW_VERSION;
const DATA_CACHE = 'rotapas-data:' + SCOPE;          // must match index.html
const DATA_URL = new URL('schedule.json', SCOPE).href;
const PAGE_URL = new URL('./', SCOPE).href;
// Filled in per event by the publish compiler (the logo and icons vary).
const SHELL_URLS = ["./","manifest.webmanifest"]
  .map(p => new URL(p, SCOPE).href);

async function refreshShell(cacheName){
  const cache = await caches.open(cacheName);
  await Promise.all(SHELL_URLS.map(async url => {
    const res = await fetch(url, { cache: 'reload' });
    if (res.ok) await cache.put(url, res);
  }));
}

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    await refreshShell(SHELL_CACHE);
    // Make sure schedule data is available offline even if the page's own
    // first load happened before this worker existed. Never overwrite a copy
    // that is already stored: the page decides when data is replaced.
    const data = await caches.open(DATA_CACHE);
    if (!(await data.match(DATA_URL))){
      try {
        const res = await fetch(DATA_URL, { cache: 'no-cache' });
        if (res.ok) await data.put(DATA_URL, res);
      } catch (e) { /* the page stores it on its next load */ }
    }
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names
      .filter(n => n.startsWith(SHELL_PREFIX) && n !== SHELL_CACHE)
      .map(n => caches.delete(n)));
    await self.clients.claim();
  })());
});

// Serve the stored copy at once; refresh it from the network in the background.
function staleWhileRevalidate(event, key){
  event.respondWith((async () => {
    const cache = await caches.open(SHELL_CACHE);
    const cached = await cache.match(key);
    const network = fetch(key, { cache: 'no-cache' }).then(res => {
      if (res.ok) return cache.put(key, res.clone()).then(() => res);
      return res;
    });
    if (cached){
      event.waitUntil(network.catch(() => {}));
      return cached;
    }
    return network;
  })());
}

self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (!url.href.startsWith(SCOPE)) return;                    // other sites / other projects

  // The page: any navigation to this schedule, with or without ?query.
  if (req.mode === 'navigate'){
    const path = url.origin + url.pathname;
    if (path === PAGE_URL || path === PAGE_URL + 'index.html') staleWhileRevalidate(event, PAGE_URL);
    return;
  }

  if (url.search) return;                                    // update checks: network only
  const clean = url.origin + url.pathname;

  if (clean === DATA_URL){
    event.respondWith((async () => {
      const cache = await caches.open(DATA_CACHE);
      const cached = await cache.match(DATA_URL);
      if (cached) return cached;
      const res = await fetch(DATA_URL, { cache: 'no-cache' });
      if (res.ok) await cache.put(DATA_URL, res.clone());
      return res;
    })());
    return;
  }

  if (SHELL_URLS.includes(clean)) staleWhileRevalidate(event, clean);
});

// "Refresh" in the page: fetch fresh page files before it reloads, in case the
// newly published data needs newer page code.
self.addEventListener('message', event => {
  if (event.data && event.data.type === 'refresh-shell'){
    const reply = () => event.ports[0] && event.ports[0].postMessage('done');
    event.waitUntil(refreshShell(SHELL_CACHE).then(reply, reply));
  }
});
